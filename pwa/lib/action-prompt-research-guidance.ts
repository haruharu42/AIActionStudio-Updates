const DEFAULT_RESEARCH_PROFILE: ResearchProfile = {
  principles: ["目的、対象者、入力事実、制約を分けて解釈する。", "未確認の情報を事実として補完しない。"],
  platform: ["媒体固有ルールがある場合は最新の公式情報を優先する。", "固定の成功法則ではなく、実際の結果から改善できる構造にする。"],
  failureModes: ["一般論を増やして具体的な完成物が弱くなる。", "未確認の数値・仕様・実績を断定する。"],
};

function numbered(items: readonly string[]): string {
  return items.map((item, index) => String(index + 1) + ". " + item).join("\n");
}

export function actionPromptResearchGuidance(context: ActionPromptResearchContext): string {
  const profile = RESEARCH_BACKED_CATEGORY_RULES[context.category] ?? DEFAULT_RESEARCH_PROFILE;
  return [
    "【公式情報ベースのカテゴリ精度基準】",
    "カテゴリ: " + context.category,
    "対象: " + context.title,
    "用途: " + context.sideHustle,
    "",
    "【設計原則】",
    numbered(profile.principles),
    "",
    "【媒体・実務基準】",
    numbered(profile.platform),
    "",
    "【失敗回避】",
    numbered(profile.failureModes),
    "",
    "媒体仕様・価格・規約・アルゴリズム・法令など更新されうる情報は、実行環境で最新確認できる場合は公式一次情報を優先し、確認できない場合は固定値として断定せず「要確認」と扱ってください。",
  ].join("\n");
}
