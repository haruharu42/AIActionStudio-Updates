const DEFAULT_TEMPLATE_GUIDANCE = [
  "テンプレート名の目的を最優先し、カテゴリ一般論より今回の完成物を具体化する。",
  "入力済み情報だけを事実として使い、未指定は提案または要確認として扱う。",
  "そのまま次工程へ使える形式で出力する。",
] as const;

function numbered(items: readonly string[]): string {
  return items.map((item, index) => String(index + 1) + ". " + item).join("\n");
}

export function actionPromptTemplateGuidance(context: ActionPromptTemplateContext): string {
  const guidance = TEMPLATE_DEDICATED_GUIDANCE[context.id] ?? DEFAULT_TEMPLATE_GUIDANCE;
  return [
    "【テンプレート専用設計】",
    "テンプレート: " + context.title,
    "カテゴリ: " + context.category,
    "用途: " + context.sideHustle,
    "",
    numbered(guidance),
    "",
    "このテンプレート固有の目的を、カテゴリ共通ルールより具体的な実行指示として優先してください。",
  ].join("\n");
}
